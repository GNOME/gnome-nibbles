Angle negative_degrees (Angle a)
{
    return Angle(-a.x, a.y);
}

void test_angles()
{
	/* The largest angle in this array must be less than 180° larger than the smallest angle. */
	const int size=9;
	Angle a[size] = {DEGREES[135]			/* 135.0° */,
				DEGREES[45]					/*  45.0° */,
				DEGREES[0]					/*   0.0° */,
				DEGREES[90]					/*  90.0° */,
				{-247785223,  -6306555056}	/*  -2.25° */,
				DEGREES[177]				/* 177.0° */,
				{1646733178, -53898011185}	/*   1.75° */,
				{3293466356,-107796022370}	/*   1.75° */,
				{-741003743, -15426829180}	/*  -2.75° */};

	std::cout << "angles: ";
	for (int d = 0; d < size; d++)
		std::cout << (std::atan2((int64_t)a[d].x, -(int64_t)a[d].y) / std::numbers::pi * 180) << "°, ";
	std::cout << std::endl;

	// bubble sort angles (assending order)
	for (int i = size; i > 0; i--)
	{
		for (int o = 0; o < i - 1; o++)
		{
		    if (a[o] > a[o + 1])
		    {
		        Angle swap(a[o]);
		        a[o]=a[o+1];
		        a[o+1]=swap;
				std::cout << "sorting assending: ";
		        for (int d = 0; d < size; d++)
		            std::cout << (std::atan2((int64_t)a[d].x, -(int64_t)a[d].y) / std::numbers::pi * 180) << "°, ";
				std::cout << std::endl;
		    }
		}
	}
	std::cout << "sorted assending: ";
	for (int d = 0; d < size; d++)
        std::cout << (std::atan2((int64_t)a[d].x, -(int64_t)a[d].y) / std::numbers::pi * 180) << "°, ";
	std::cout << std::endl;
	for (int d = 0; d < size - 1; d++)
		assert (a[d] <= a[d + 1]); // angles should be sorted in to assending order

	// bubble sort angles (descending order)
	for (int i = size; i > 0; i--)
	{
		for (int o = 0; o < i - 1; o++)
		{
		    if (a[o] < a[o + 1])
		    {
		        Angle swap(a[o]);
		        a[o]=a[o + 1];
		        a[o + 1]=swap;
				std::cout << "sorting desending: ";
		        for (int d = 0; d < size; d++)
		            std::cout << (std::atan2((int64_t)a[d].x, -(int64_t)a[d].y) / std::numbers::pi * 180) << "°, ";
				std::cout << std::endl;
		    }
		}
	}
	std::cout << "sorted desending: ";
	for (int d = 0; d < size; d++)
        std::cout << (std::atan2((int64_t)a[d].x, -(int64_t)a[d].y) / std::numbers::pi * 180) << "°, ";
	std::cout << std::endl;
	for (int d = 0; d < size - 1; d++)
		assert (a[d] >= a[d + 1]); // angles should be sorted in to descending order

	// test angle wrap around
	a[0] = DEGREES[136];                   /* 136.0° */
	a[1] = negative_degrees (DEGREES[45]); /* -45.0° */
	assert (a[0] < a[1]);

	// test quarter wrap around
	a[0] = { 0, -1}; /*   0° */
	a[1] = {+1,  0}; /*  90° */
	a[2] = { 0, +1}; /* 180° */
	a[3] = {-1,  0}; /* -90° */
	assert (a[0] > a[3]);
	assert (a[0] < a[1]);
	assert (a[1] > a[0]);
	assert (a[1] < a[2]);
	assert (a[2] > a[1]);
	assert (a[2] < a[3]);
	assert (a[3] > a[2]);
	assert (a[3] < a[0]);

	// test equality
	a[0] = { 0, +1}; /* 180° */
	a[1] = { 0, -1}; /*   0° */
	a[2] = {+1, +1}; /*  45° */
	a[3] = {+3, +3}; /*  45° */
	a[4] = {-3, -3}; /* -45° */
	assert(a[0]!=a[1]);
	assert(a[2]!=a[4]);
	assert(!(a[2]>a[4]));
	assert(!(a[2]>=a[4]));
	assert(a[2]==a[3]);
}

struct WormTest
{
	uint8_t start_x,start_y,final_lives,final_score,final_length;
};

class TestWorms
{
public:
	TestWorms(std::initializer_list<std::initializer_list<uint8_t>> rows)
	{
		assert(rows.size()>0);
		for (const auto& row : rows)
		{
			assert(row.size()==5);
			auto i=row.begin();
            data.emplace_back/*append*/(WormTest({*i,*(i+1),*(i+2),*(i+3),*(i+4)}));
		}
	}
	auto get_count() {return data.size();}
	auto get(unsigned long i)
	{
		return data[i];
	}
private:
	std::vector<WormTest> data;
};

void test_board(const std::span<const std::string_view> &strings,
				uint8_t regular_bonuse_count,
				uint8_t bonuses_eaten,
				TestWorms worms)
{
	Game game(regular_bonuse_count);
    game.load_board(strings);
    game.create_worms(0, worms.get_count());
    game.spawn_worms(true/*force_materialize*/);
    for(const Worm &worm : game.get_worms())
    {
    	std::cout << "worm " << (unsigned long)worm.get_colour() << " head at " << (unsigned long)worm.get_positions().get_head().x <<
    		"," << (unsigned long)worm.get_positions().get_head().y << " should be at " << (unsigned long)worms.get(worm.get_colour()).start_x <<
    		"," << (unsigned long)worms.get(worm.get_colour()).start_y << std::endl;
	}
    for(const Worm &worm : game.get_worms())
    {
    	assert(worm.get_positions().get_head().x == worms.get(worm.get_colour()).start_x);
		assert(worm.get_positions().get_head().y == worms.get(worm.get_colour()).start_y);
	}
    game.add_bonus(true);
    for(game.print_board();game.get_game_status()==Game::ACTIVE; game.move_worms())
    {
		if(regular_bonuse_count<=2)
			game.print_board();
    }
	game.print_board();
    
    for(const Worm &worm : game.get_worms())
    {
    	std::cout << "worm " << (unsigned long)worm.get_colour() << " final lives: " << worm.get_lives() << 
    		" should be " << (unsigned long)worms.get(worm.get_colour()).final_lives << std::endl;
    	std::cout << "worm " << (unsigned long)worm.get_colour() << " final score: " << worm.get_score() << 
    		" should be " << (unsigned long)worms.get(worm.get_colour()).final_score << std::endl;
    	std::cout << "worm " << (unsigned long)worm.get_colour() << " final length: " << worm.get_target_length() << 
    		" should be " << (unsigned long)worms.get(worm.get_colour()).final_length << std::endl;
    }
    std::cout << "bonuses eaten: " << (unsigned long)game.get_regular_bonuses_consumed() <<
    	" should be " << (unsigned long)bonuses_eaten << std::endl;
    
    for(const Worm &worm : game.get_worms())
    {
		assert(worm.get_lives() == worms.get(worm.get_colour()).final_lives);
		assert(worm.get_score() == worms.get(worm.get_colour()).final_score);
		assert(worm.get_target_length()== worms.get(worm.get_colour()).final_length);
    }
	assert(game.get_regular_bonuses_consumed()==bonuses_eaten);
    
    
}

